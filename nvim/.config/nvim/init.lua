-- Prose files: soft wrap, spell, concealed markup
vim.api.nvim_create_autocmd("FileType", {
  pattern = { "markdown", "text", "gitcommit" },
  callback = function()
    local l = vim.opt_local
    l.wrap, l.linebreak, l.breakindent = true, true, true
    l.spell, l.spelllang = true, "en"
    l.conceallevel = 2
  end,
})

-- Treesitter highlighting wherever a parser exists
vim.api.nvim_create_autocmd("FileType", {
  callback = function() pcall(vim.treesitter.start) end,
})

vim.api.nvim_create_autocmd({ "InsertLeave", "TextChanged" }, {
  pattern = "*.md",
  command = "silent! write",
})

vim.api.nvim_create_autocmd("TextYankPost", {
  callback = function() vim.hl.on_yank({ timeout = 150 }) end,
})

-- matugen post_hook sends SIGUSR1 after a wallpaper / light-dark switch
vim.api.nvim_create_autocmd("Signal", {
  pattern = "SIGUSR1",
  callback = function() pcall(vim.cmd.colorscheme, "matugen") end,
})

vim.diagnostic.config({ virtual_text = true, severity_sort = true })

-- Keymaps ------------------------------------------------------------------
local map = function(lhs, rhs, desc, mode) vim.keymap.set(mode or "n", lhs, rhs, { desc = desc }) end
local fzf = function(fn, opts) return function() require("fzf-lua")[fn](opts) end end

map("jk", "<Esc>", "Escape", "i")
map("<C-s>", "<Cmd>w<CR>", "Save", { "n", "i", "v" })
map("<Esc>", "<Cmd>nohlsearch<CR>", "Clear search")
map("<C-h>", "<C-w>h", "Window left")
map("<C-j>", "<C-w>j", "Window down")
map("<C-k>", "<C-w>k", "Window up")
map("<C-l>", "<C-w>l", "Window right")
map("<S-h>", "<Cmd>bprevious<CR>", "Prev buffer")
map("<S-l>", "<Cmd>bnext<CR>", "Next buffer")
map("<leader>q", "<Cmd>bdelete<CR>", "Close buffer")
map("<leader>e", "<Cmd>Oil<CR>", "File explorer")

map("<leader>ff", fzf("files"), "Find files")
map("<leader>fg", fzf("live_grep"), "Grep")
map("<leader>fb", fzf("buffers"), "Buffers")
