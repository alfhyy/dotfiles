map("<leader>nd", function() vim.cmd.edit(notes .. "/" .. os.date("%Y-%m-%d") .. ".md") end, "Daily note")
map("<leader>nn", function()
  vim.ui.input({ prompt = "Note title: " }, function(t)
    if t and t ~= "" then vim.cmd.edit(notes .. "/" .. t:gsub("%s+", "-"):lower() .. ".md") end
  end)
end, "New note")
map("<leader>nf", fzf("files", { cwd = notes }), "Find note")
map("<leader>ng", fzf("live_grep", { cwd = notes }), "Grep notes")
map("<leader>nt", "<Cmd>RenderMarkdown toggle<CR>", "Toggle markdown render")

map("<leader>gb", "<Cmd>Gitsigns blame_line<CR>", "Blame line")
